-- 1. Tabela de Utilizadores (Admins e Revendedores)
CREATE TABLE IF NOT EXISTS public.utilizadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    username TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    desconto NUMERIC(5,2) NOT NULL DEFAULT 0,
    role TEXT NOT NULL DEFAULT 'revendedor', -- 'admin' ou 'revendedor'
    ativo BOOLEAN NOT NULL DEFAULT true,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Tabela de Encomendas
CREATE TABLE IF NOT EXISTS public.encomendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revendedor_id BIGINT REFERENCES public.utilizadores(id) ON DELETE SET NULL,
    revendedor_nome TEXT NOT NULL,
    revendedor_username TEXT NOT NULL,
    desconto_aplicado NUMERIC(5,2) NOT NULL DEFAULT 0,
    itens JSONB NOT NULL DEFAULT '[]'::jsonb,
    subtotal_publico NUMERIC(10,2) NOT NULL DEFAULT 0,
    total_revenda NUMERIC(10,2) NOT NULL DEFAULT 0,
    notas TEXT DEFAULT '',
    estado TEXT NOT NULL DEFAULT 'pendente', -- 'pendente', 'preparacao', 'entregue', 'cancelada'
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Garantir permissões de acesso à API (mesmo que a opção automática não tenha sido marcada)
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.utilizadores TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.encomendas TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 4. Ativar Row Level Security (RLS) com políticas abertas para a API do catálogo
ALTER TABLE public.utilizadores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.encomendas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Acesso total utilizadores" ON public.utilizadores;
CREATE POLICY "Acesso total utilizadores" ON public.utilizadores FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso total encomendas" ON public.encomendas;
CREATE POLICY "Acesso total encomendas" ON public.encomendas FOR ALL USING (true) WITH CHECK (true);

